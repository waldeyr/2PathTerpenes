// Optional browser regression. Requires Playwright and Chrome installed:
// node tests/browser_scale.cjs /tmp/2path-stress/report/hypergraph.html
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { resolve } = require('node:path');
const { chromium } = require('playwright');

(async () => {
  assert.ok(process.argv[2], 'Pass the HTML generated by tests/stress_pipeline.py');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(String(error)));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    await page.goto(pathToFileURL(resolve(process.argv[2])).href);
    const counts = await page.evaluate(() => ({
      nodes: document.querySelectorAll('.hg-node').length,
      edges: document.querySelectorAll('.hg-hyperedge').length,
      links: document.querySelectorAll('.hg-link').length,
      firstNodeWidth: document.querySelector('.hg-node circle')?.getBoundingClientRect().width || 0,
      firstNodeVisible: (() => {
        const node = document.querySelector('.hg-node circle')?.getBoundingClientRect();
        const canvas = document.querySelector('#hg-canvas').getBoundingClientRect();
        return !!node && node.right > canvas.left && node.left < canvas.right &&
          node.bottom > canvas.top && node.top < canvas.bottom;
      })(),
      readyMs: performance.getEntriesByType('navigation')[0].domContentLoadedEventEnd,
      total: JSON.parse(document.querySelector('#hg-data').textContent).nodes.length
    }));
    assert.ok(counts.nodes <= 500 && counts.edges <= 500 && counts.links <= 2000);
    assert.ok(counts.firstNodeVisible && counts.firstNodeWidth >= 8,
      'initial large-graph view must contain a human-visible station');
    const last = counts.total - 1;
    await page.locator('#hg-search').fill(`Molecule ${last}`);
    await page.waitForFunction(id => document.querySelector('#hg-status').textContent.includes('1 match') &&
      !!document.querySelector(`[data-node="v${id}"]`), last);
    await page.locator(`[data-node="v${last}"]`).dispatchEvent('click');
    await page.waitForFunction(() => {
      const image = document.querySelector('.hg-molecule-image');
      return image && image.complete && image.naturalWidth > 0;
    });
    await page.locator('#hg-pathway').selectOption(`v${last}`);
    assert.match(await page.locator('#hg-details').innerText(), /1 reaction step/);
    await page.locator('#hg-reset').click();
    await page.locator('#hg-next').click();
    assert.match(await page.locator('#hg-page').innerText(), /Page 2 /);
    await page.locator('#hg-prev').click();
    assert.match(await page.locator('#hg-page').innerText(), /Page 1 /);
    await page.locator('#hg-search').fill('no-such-molecule');
    await page.waitForFunction(() => document.querySelectorAll('.hg-node').length === 0);
    for (let i = 0; i < 10; i++) {
      await page.locator('#hg-reset').click();
      await page.locator('#hg-next').click();
    }
    assert.ok(await page.locator('svg *').count() < 10000, 'DOM grows after repeated redraws');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ ...counts, interactionsPassed: true, consoleErrors: errors }, null, 2));
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
